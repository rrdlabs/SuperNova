static sn_test_key_t s_keys[SN_TEST_KEY_COUNT];
static bool s_ready;

esp_err_t sn_app_test_keys_init(void)
{
    if (s_ready) {
        return ESP_OK;
    }
    memset(s_keys, 0, sizeof(s_keys));
    for (size_t i = 0; i < SN_TEST_KEY_COUNT; i++) {
        esp_err_t err = sn_soft_signer_init(&s_keys[i].signer, s_test_scalars[i]);
        if (err != ESP_OK) {
            sn_app_test_keys_deinit();
            return err;
        }
        err = sn_soft_signer_get_pubkey(&s_keys[i].signer, s_keys[i].pubkey);
        if (err != ESP_OK) {
            sn_app_test_keys_deinit();
            return err;
        }
        s_keys[i].ready = true;
    }
    s_ready = true;
    return ESP_OK;
}

void sn_app_test_keys_deinit(void)
{
    for (size_t i = 0; i < SN_TEST_KEY_COUNT; i++) {
        if (s_keys[i].ready) {
            sn_soft_signer_deinit(&s_keys[i].signer);
        }
        memset(&s_keys[i], 0, sizeof(s_keys[i]));
    }
    s_ready = false;
}

const sn_test_key_t *sn_app_test_key(size_t index)
{
    if (!s_ready || index >= SN_TEST_KEY_COUNT || !s_keys[index].ready) {
        return NULL;
    }
    return &s_keys[index];
}

sn_signer_t sn_app_test_signer(size_t index)
{
    const sn_test_key_t *key = sn_app_test_key(index);
    if (key == NULL) {
        sn_signer_t invalid = {0};
        return invalid;
    }
    return sn_soft_signer_as_signer((sn_soft_signer_t *)&key->signer);
}

int sn_app_test_key_index_for_pubkey(const uint8_t pubkey[SN_PUBKEY_LEN])
{
    if (!s_ready || pubkey == NULL) {
        return -1;
    }
    for (size_t i = 0; i < SN_TEST_KEY_COUNT; i++) {
        if (s_keys[i].ready &&
            memcmp(s_keys[i].pubkey, pubkey, SN_PUBKEY_LEN) == 0) {
            return (int)i;
        }
    }
    return -1;
}
