#!/usr/bin/env python3
"""Independent reference vectors for the SuperNova Phase 2 wire format.

This generator implements the protocol from the written specification using
only the Python standard library. It deliberately does not import or execute the
C implementation. The emitted header is compared byte-for-byte by the firmware
test suite, so a C encoder change that disagrees with the specification fails.

The canonical transaction uses a fixed placeholder signature. The vector tests
encoding and hashing, not signature validity; signature accept/reject is tested
separately with the software test-key signer.

Run from the phase_2 directory:

    python3 tools/gen_vectors.py

The output path is components/sn_app/include/sn_app_test_vectors.h.
"""

from __future__ import annotations

import hashlib
import struct
from pathlib import Path

# P-256 generator point, uncompressed. Used only as a fixed valid public key in
# the encoding vector. This is public, standard curve data, not a secret.
GX = bytes.fromhex(
    "6B17D1F2E12C4247F8BCE6E563A440F277037D812DEB33A0F4A13945D898C296"
)
GY = bytes.fromhex(
    "4FE342E2FE1A7F9B8EE7EB4A7C0F9E162BCE33576B315ECECBB6406837BF51F5"
)
PUBKEY = b"\x04" + GX + GY


def sha256(data: bytes) -> bytes:
    return hashlib.sha256(data).digest()


def domain_hash(domain: str, data: bytes) -> bytes:
    return sha256(domain.encode("ascii") + data)


def u8(value: int) -> bytes:
    return struct.pack(">B", value)


def u16(value: int) -> bytes:
    return struct.pack(">H", value)


def u32(value: int) -> bytes:
    return struct.pack(">I", value)


def u64(value: int) -> bytes:
    return struct.pack(">Q", value)


def tx_encoding(with_signature: bool) -> bytes:
    prev_txid = bytes(range(0x00, 0x20))
    signature = bytes(range(0xA0, 0xE0))
    out = bytearray()
    out += u16(1)  # version
    out += u8(0x02)  # test network
    out += u16(1)  # input count
    out += prev_txid
    out += u32(7)  # previous output index
    out += PUBKEY
    out += u8(1)  # ECDSA P-256/SHA-256
    if with_signature:
        out += signature
    out += u16(2)  # output count
    for value in (1000, 500):
        out += u64(value)
        out += PUBKEY
    return bytes(out)


def build() -> dict[str, bytes]:
    tx_unsigned = tx_encoding(False)
    tx_full = tx_encoding(True)
    txid = domain_hash("SN2/TXID/v1", tx_full)
    tx_digest = domain_hash("SN2/TXSIG/v1", tx_unsigned)

    prev_block_hash = bytes(range(0x20, 0x40))
    state_root = bytes(range(0x40, 0x60))
    timestamp = 0x0102030405060708
    tx_root = domain_hash("SN2/TXROOT/v1", txid)

    header = bytearray()
    header += u16(1)  # version
    header += u8(0x02)  # test network
    header += u32(1)  # height
    header += prev_block_hash
    header += u64(timestamp)
    header += u16(1)  # tx count
    header += tx_root
    header += state_root
    header += PUBKEY
    assert len(header) == 178

    block_full = bytes(header) + u16(len(tx_full)) + tx_full
    block_hash = domain_hash("SN2/BLOCKID/v1", bytes(header))
    block_digest = domain_hash("SN2/BLOCKSIG/v1", block_hash)

    vote_block_hash = bytes(range(0x60, 0x80))
    vote_digest = domain_hash(
        "SN2/VOTE/v1",
        u32(1) + u32(0) + vote_block_hash + u8(2) + u8(1),
    )

    genesis_txid = domain_hash("SN2/GENESIS/v1", u8(0x02))

    return {
        "sn_vector_pubkey": PUBKEY,
        "sn_vector_tx_signature": bytes(range(0xA0, 0xE0)),
        "sn_vector_tx_unsigned": tx_unsigned,
        "sn_vector_tx_full": tx_full,
        "sn_vector_txid": txid,
        "sn_vector_tx_signing_digest": tx_digest,
        "sn_vector_tx_root": tx_root,
        "sn_vector_block_header": bytes(header),
        "sn_vector_block_full": block_full,
        "sn_vector_block_hash": block_hash,
        "sn_vector_block_signing_digest": block_digest,
        "sn_vector_vote_digest": vote_digest,
        "sn_vector_genesis_txid": genesis_txid,
    }


def c_array(name: str, data: bytes) -> str:
    lines = [f"static const uint8_t {name}[] = {{"]
    for i in range(0, len(data), 12):
        chunk = data[i : i + 12]
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in chunk) + ",")
    lines.append("};")
    return "\n".join(lines)


def main() -> None:
    vectors = build()
    out = [
        "/* Generated by tools/gen_vectors.py. Do not edit by hand. */",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "#define SN_VECTOR_TX_UNSIGNED_LEN "
        + str(len(vectors["sn_vector_tx_unsigned"])),
        "#define SN_VECTOR_TX_FULL_LEN "
        + str(len(vectors["sn_vector_tx_full"])),
        "#define SN_VECTOR_BLOCK_HEADER_LEN "
        + str(len(vectors["sn_vector_block_header"])),
        "#define SN_VECTOR_BLOCK_FULL_LEN "
        + str(len(vectors["sn_vector_block_full"])),
        "",
    ]
    for name, data in vectors.items():
        out.append(c_array(name, data))
        out.append("")
    text = "\n".join(out)

    root = Path(__file__).resolve().parent.parent
    dest = root / "components" / "sn_app" / "include" / "sn_app_test_vectors.h"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(text, encoding="ascii")
    print(f"wrote {dest}")
    print(f"tx_unsigned={len(vectors['sn_vector_tx_unsigned'])} bytes")
    print(f"tx_full={len(vectors['sn_vector_tx_full'])} bytes")
    print(f"block_full={len(vectors['sn_vector_block_full'])} bytes")
    print("txid=" + vectors["sn_vector_txid"].hex())
    print("block_hash=" + vectors["sn_vector_block_hash"].hex())


if __name__ == "__main__":
    main()
